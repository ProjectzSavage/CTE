--[[
	Config
	======
	Single source of truth for EVERY tunable number in Clutch the Egg.

	DataModel location : ReplicatedStorage.Modules.Config  (ModuleScript)
	Repo location      : src/ReplicatedStorage/Modules/Config.lua

	Rules
	-----
	* Gameplay code must never hard-code numbers -- always read them from here.
	* The client may read this module for HUD/prediction, but the SERVER is the
	  only authority that acts on it (server-authoritative design).
	* The Arena* section documents the pre-built geometry that lives in
	  Workspace.Arena (generated by tools/gen_arena.py). If you change a value
	  here, regenerate the arena so they stay in sync.

	NOTE: Gameplay is NOT implemented yet. These are the tuned starting values
	the systems will read once they are built.
--]]

local Config = {}

--------------------------------------------------------------------------
-- Match flow
--------------------------------------------------------------------------
Config.MaxPlayers = 6            -- hard player cap for the arena
Config.MinPlayersToStart = 1     -- TODO: raise once matchmaking exists (1 = solo testing)
Config.RoundLength = 75          -- seconds per round
Config.RoundsPerMatch = 3        -- best of 3
Config.RoundsToWinMatch = 2      -- first to 2 round wins takes the match
Config.RoundStartCountdown = 3   -- "3.. 2.. 1.. GO!" before a round begins
Config.RoundEndFreeze = 4        -- seconds of post-round results freeze
Config.IntermissionLength = 8    -- seconds between matches

--------------------------------------------------------------------------
-- Scoring / hold time
--------------------------------------------------------------------------
-- Round winner = most TOTAL hold time in that round.
-- Match MVP    = most hold time across ALL rounds.
Config.HoldTimeSyncInterval = 0.1 -- seconds between server HoldTimeUpdated broadcasts

--------------------------------------------------------------------------
-- Movement
--------------------------------------------------------------------------
Config.WalkSpeed = 16            -- empty-handed speed
Config.CarrySpeed = 12           -- speed while holding the egg
Config.JumpPower = 50            -- standard Roblox jump

--------------------------------------------------------------------------
-- Dash (always enabled)
--------------------------------------------------------------------------
Config.DashSpeedBonus = 24       -- added on top of current WalkSpeed for the burst
Config.DashDuration = 0.25       -- seconds
Config.DashCooldown = 2.5        -- seconds
Config.DashStaminaCost = 25
Config.DashIFrames = 0.2         -- invulnerability window while dashing WITHOUT the egg

-- While CARRYING the egg the dash is shorter, grants NO i-frames, and dashing
-- into a player makes the carrier drop the egg (see EggDropOnDashCollision).
Config.DashSpeedBonusCarrying = 16
Config.DashDurationCarrying = 0.15
Config.DashCooldownCarrying = 2.5
Config.DashStaminaCostCarrying = 30
Config.DashIFramesCarrying = 0

--------------------------------------------------------------------------
-- Attack (punch -- enabled ONLY when NOT holding the egg; "HANDS FULL" otherwise)
--------------------------------------------------------------------------
-- Hitting the carrier knocks the egg loose.
Config.AttackRange = 5           -- studs in front of the attacker
Config.AttackKnockback = 25      -- horizontal impulse applied to the victim
Config.AttackUpwardKnockback = 8 -- small pop-up so hits feel chunky
Config.AttackCooldown = 0.6      -- seconds
Config.AttackStaminaCost = 10
Config.AttackHitstun = 0.25      -- brief control loss for the victim

--------------------------------------------------------------------------
-- Throw (enabled ONLY while holding the egg)
--------------------------------------------------------------------------
Config.ThrowSpeed = 60           -- egg launch speed (studs/s)
Config.ThrowUpwardBias = 12      -- extra vertical component: it is a LOB, not a laser
Config.ThrowSelfPickupDelay = 0.8 -- cannot re-grab your OWN throw/fumble for this long

--------------------------------------------------------------------------
-- Block (always enabled)
--------------------------------------------------------------------------
-- Reduces incoming knockback. While holding the egg you STILL accrue hold
-- time when blocking, but you move at BlockSpeedMultiplier.
Config.BlockKnockbackReduction = 0.6 -- fraction of knockback removed (0.6 = 60% less)
Config.BlockSpeedMultiplier = 0.5    -- 50% move speed while blocking (carrying or not)
Config.BlockStaminaDrain = 15        -- stamina drained per second while holding block

--------------------------------------------------------------------------
-- Stamina (shared resource for Dash / Attack / Block)
--------------------------------------------------------------------------
Config.StaminaMax = 100
Config.StaminaRegenPerSecond = 20
Config.StaminaRegenDelay = 0.75 -- seconds after spending before regen resumes

--------------------------------------------------------------------------
-- Egg
--------------------------------------------------------------------------
Config.EggRadius = 1                  -- simple glowing sphere for now (art polish later)
Config.EggCarryOffsetUp = 0.75        -- weld offset above the torso part (studs)
Config.EggCarryOffsetForward = 1.5    -- weld offset in front of the torso (studs)
Config.EggRespawnDelay = 3            -- seconds out-of-arena OR unclaimed before center respawn
Config.EggDropOnDashCollision = true  -- carrier dashes into a player -> egg drops
Config.EggKnockLooseSpeed = 20        -- pop-off speed when the carrier is punched
Config.EggKnockLooseUpward = 10
Config.HoldTimePausesWhenLoose = true -- nobody accrues hold time while the egg is loose/respawning
Config.EggProximityPickupRadius = 3   -- backup pickup scan radius around the loose egg (studs)
Config.EggOutOfBoundsY = -40          -- below this Y the egg counts as fallen out of the arena
Config.EggOutOfBoundsHorizontal = 70  -- beyond this |X|/|Z| counts as out of the arena
Config.EggLooseResetRadius = 8        -- unclaimed egg farther than this from center resets to center
Config.EggFumblePop = 4               -- gentle upward velocity when a fumble drops the egg (studs/s)

--------------------------------------------------------------------------
-- Arena (documents the BUILT geometry -- keep in sync with tools/gen_arena.py)
--------------------------------------------------------------------------
Config.ArenaFloorSize = 128       -- outer floor slab, studs (playable square is 120x120 inside the walls)
Config.ArenaPlaySize = 120        -- playable square: wall inner faces sit at +/-60 on X/Z
Config.ArenaWallHeight = 5
Config.ArenaWallThickness = 2
Config.ArenaSpawnRadius = 48      -- distance of the 6 spawn pads from center
Config.ArenaSpawnCount = 6
Config.ArenaEggSpawnHeight = 3    -- Y of the Workspace.Arena.EggSpawnPoint marker

--------------------------------------------------------------------------
-- Debug
--------------------------------------------------------------------------
Config.DebugVerboseLogging = true -- services log lifecycle events when true

return Config
